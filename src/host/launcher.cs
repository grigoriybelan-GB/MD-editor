    // High-quality square header icon, downscaled with bicubic. Loads a PNG (md-editor-icon.png),
    // NOT the .ico — this .ico's frames are PNG-compressed and GDI+'s Icon.ToBitmap()/DrawIcon throw
    // or render garbage on them (the Windows shell decodes them fine, hence the OK taskbar icon).
    static Image LoadHeaderIcon(string pngPath, int size)
    {
        using (var src = Image.FromFile(pngPath))
        {
            var bmp = new Bitmap(size, size);
            using (var g = Graphics.FromImage(bmp))
            {
                g.InterpolationMode = System.Drawing.Drawing2D.InterpolationMode.HighQualityBicubic;
                g.PixelOffsetMode   = System.Drawing.Drawing2D.PixelOffsetMode.HighQuality;
                g.SmoothingMode     = System.Drawing.Drawing2D.SmoothingMode.HighQuality;
                g.Clear(Color.Transparent);
                g.DrawImage(src, new Rectangle(0, 0, size, size));
            }
            return bmp;
        }
    }

    static void OpenExternal(string url)
    {
        if (string.IsNullOrEmpty(url)) return;
        try { Process.Start(new ProcessStartInfo { FileName = url, UseShellExecute = true }); }
        catch { /* no handler / blocked — silently ignore */ }
    }

    // True when visually maximized — our manual maximize, or an OS maximize from Aero Snap.
    bool IsMaxView { get { return _isMax || WindowState == FormWindowState.Maximized; } }

    // Maximize MANUALLY to the work area of the monitor the window is currently on. OS maximize
    // (WindowState.Maximized) of this borderless WS_THICKFRAME window jumps to monitor 1 regardless
    // of where the window sits; sizing to Screen.FromHandle(...).WorkingArea keeps it on THIS screen.
    void ToggleMax()
    {
        if (IsMaxView)
        {
            if (WindowState == FormWindowState.Maximized) WindowState = FormWindowState.Normal; // undo an Aero snap
            if (_isMax) { _isMax = false; Bounds = _restoreBounds; }
        }
        else
        {
            _restoreBounds = Bounds;
            _isMax = true;
            Bounds = Screen.FromHandle(Handle).WorkingArea; // current monitor's work area
        }
        LayoutAll();
        Invalidate();
        if (btnMax != null) btnMax.Text = ((char)(IsMaxView ? 0xE923 : 0xE922)).ToString();
    }


    void LayoutAll()
    {
        // When maximized there are no resize borders (and snapping covers the work area), so the
        // WebView2 fills edge-to-edge; when normal it's inset by RESIZE on L/R/bottom to expose the
        // form's own edges to WM_NCHITTEST (see WndProc) — that exposed strip is the resize border.
        int b = IsMaxView ? 0 : RESIZE;
        titleBar.SetBounds(0, 0, ClientSize.Width, TITLE_H);
        web.SetBounds(b, TITLE_H,
            Math.Max(0, ClientSize.Width - b * 2),
            Math.Max(0, ClientSize.Height - TITLE_H - b));
        LayoutTitleBar();
    }

    void LayoutTitleBar()
    {
        int bw = 46;
        btnClose.SetBounds(titleBar.Width - bw,     0, bw, TITLE_H);
        btnMax  .SetBounds(titleBar.Width - bw * 2, 0, bw, TITLE_H);
        btnMin  .SetBounds(titleBar.Width - bw * 3, 0, bw, TITLE_H);

        int x = 10;
        if (appIcon != null) { appIcon.SetBounds(x, (TITLE_H - 20) / 2, 20, 20); x += 26; }
        appLabel.SetBounds(x, 0, 96, TITLE_H);

        // Full-width centered label (kept behind the edge controls).
        fileLabel.SetBounds(0, 0, titleBar.Width, TITLE_H);
        fileLabel.SendToBack();
    }

    // A crisp 1px frame around the window so the (resizable) border reads as an intentional edge,
    // not just dark padding. Drawn in the exposed L/R/bottom strips that the WebView2 doesn't cover.
    protected override void OnPaint(PaintEventArgs e)
    {
        base.OnPaint(e);
        if (IsMaxView) return;
        using (var pen = new Pen(BORDER_COLOR))
            e.Graphics.DrawRectangle(pen, 0, 0, ClientSize.Width - 1, ClientSize.Height - 1);
    }

    protected override void OnResize(EventArgs e)
    {
        base.OnResize(e);
        if (titleBar == null || web == null) return;
        LayoutAll();
        Invalidate(); // repaint the frame after the edges move
        // Sync the maximize/restore glyph (covers Aero snap too, not just the button / double-click).
        if (btnMax != null)
            btnMax.Text = ((char)(IsMaxView ? 0xE923 : 0xE922)).ToString();
    }

    // Warn before discarding unsaved changes. _dirty is mirrored from the page (DIRTY: messages);
    // covers every close path — the custom close button, Alt+F4, and the taskbar close. Offers
    // Save and close / Close (discard) / Cancel. "Save and close" defers the close: the page saves
    // (handling Save As for untitled docs) and signals CLOSENOW, which re-closes with _forceClose.
    protected override void OnFormClosing(FormClosingEventArgs e)
    {
        if (_dirty && !_forceClose)
        {
            switch (AskUnsavedChoice())
            {
                case UnsavedChoice.Cancel:
                    e.Cancel = true; return;
                case UnsavedChoice.SaveAndClose:
                    e.Cancel = true;
                    try { web.CoreWebView2.PostWebMessageAsString("SAVEFORCLOSE"); }
                    catch { e.Cancel = false; } // bridge gone — just close
                    return;
                // UnsavedChoice.Close → fall through and close without saving.
            }
        }
        base.OnFormClosing(e);
    }

    enum UnsavedChoice { SaveAndClose, Close, Cancel }

    // Small modal dialog with three explicit choices (MessageBox can't relabel its buttons).
    UnsavedChoice AskUnsavedChoice()
    {
        using (var dlg = new Form())
        {
            dlg.Text            = "Unsaved changes";
            dlg.FormBorderStyle = FormBorderStyle.FixedDialog;
            dlg.StartPosition   = FormStartPosition.CenterParent;
            dlg.MinimizeBox     = false; dlg.MaximizeBox = false; dlg.ShowIcon = false;
            dlg.ClientSize      = new Size(440, 132);
            // Match the app's dark theme: dark client + dark OS title bar.
            dlg.BackColor       = Color.FromArgb(0x25, 0x25, 0x26);
            dlg.ForeColor       = Color.FromArgb(0xcc, 0xcc, 0xcc);
            dlg.Font            = new Font("Segoe UI", 9.75F);
            dlg.HandleCreated  += delegate(object s, EventArgs ev) { UseDarkTitleBar(dlg.Handle); };

            dlg.Controls.Add(new Label
            {
                Text = "You have unsaved changes. What would you like to do?",
                AutoSize = false, Bounds = new Rectangle(18, 20, 404, 40),
                ForeColor = Color.FromArgb(0xd4, 0xd4, 0xd4), BackColor = Color.Transparent,
                Font = new Font("Segoe UI", 9.75F)
            });

            // No Cancel button — the dialog's own ✕ (and Esc) cancels, returning DialogResult.Cancel.
            var bSave  = new Button { Text = "Save and close", DialogResult = DialogResult.Yes };
            var bClose = new Button { Text = "Close",          DialogResult = DialogResult.No };
            bClose.SetBounds(348, 84,  80, 30);   // right-aligned: 440 - 12 - 80
            bSave .SetBounds(230, 84, 110, 30);   // 348 - 8 - 110
            StyleDialogButton(bSave,  true);      // accent blue — the default/recommended action
            StyleDialogButton(bClose, false);     // neutral dark
            dlg.Controls.Add(bSave); dlg.Controls.Add(bClose);
            dlg.AcceptButton = bSave;
            dlg.KeyPreview = true;
            dlg.KeyDown += delegate(object s, KeyEventArgs ke) { if (ke.KeyCode == Keys.Escape) dlg.Close(); };

            var r = dlg.ShowDialog(this);
            if (r == DialogResult.Yes) return UnsavedChoice.SaveAndClose;
            if (r == DialogResult.No)  return UnsavedChoice.Close;
            return UnsavedChoice.Cancel;
        }
    }

    // Aero Snap (drag-to-edge, Win+Arrow, snap layouts) only works on windows that carry
    // WS_THICKFRAME + WS_MAXIMIZEBOX. FormBorderStyle.None removes them, so we add them back here;
    // WM_NCCALCSIZE (below) then strips the native frame so the window stays visually borderless.
    protected override CreateParams CreateParams
    {
        get
        {
            var cp = base.CreateParams;
            cp.Style |= WS_THICKFRAME | WS_MAXIMIZEBOX | WS_MINIMIZEBOX | WS_SYSMENU;
            return cp;
        }
    }

    protected override void WndProc(ref Message m)
    {
        // Make the client area span the whole window (no native border / caption drawn), so the
        // WS_THICKFRAME we added for snap doesn't inset our layout or paint OS chrome over it.
        if (m.Msg == WM_NCCALCSIZE && m.WParam != IntPtr.Zero) { m.Result = IntPtr.Zero; return; }
        // Stop DefWindowProc from (re)painting the native caption — without this, the OS title bar
        // reappears when the window is maximized or Aero-snapped. lParam = -1 means "don't change
        // the non-client area to reflect the active/inactive state."
        if (m.Msg == WM_NCACTIVATE) { m.LParam = (IntPtr)(-1); base.WndProc(ref m); return; }
        // Pin maximize (button, double-click caption, and snap-to-top) to the CURRENT monitor's work
        // area. Borderless WS_THICKFRAME windows otherwise maximize off-screen/oversized (the window
        // "disappears") because the default thick-frame maximize sits at a negative origin.
        if (m.Msg == WM_GETMINMAXINFO)
        {
            var mmi = (MINMAXINFO)Marshal.PtrToStructure(m.LParam, typeof(MINMAXINFO));
            var mi = new MONITORINFO { cbSize = Marshal.SizeOf(typeof(MONITORINFO)) };
            if (GetMonitorInfo(MonitorFromWindow(Handle, MONITOR_DEFAULTTONEAREST), ref mi))
            {
                mmi.ptMaxPosition.X = mi.rcWork.left - mi.rcMonitor.left;
                mmi.ptMaxPosition.Y = mi.rcWork.top  - mi.rcMonitor.top;
                mmi.ptMaxSize.X     = mi.rcWork.right  - mi.rcWork.left;
                mmi.ptMaxSize.Y     = mi.rcWork.bottom - mi.rcWork.top;
                mmi.ptMinTrackSize.X = MinimumSize.Width;
                mmi.ptMinTrackSize.Y = MinimumSize.Height;
                Marshal.StructureToPtr(mmi, m.LParam, true);
            }
            return;
        }

        if (m.Msg == WM_NCHITTEST)
        {
            int lp = m.LParam.ToInt32();
            int sx = (short)(lp & 0xFFFF), sy = (short)((lp >> 16) & 0xFFFF);
            Point p = PointToClient(new Point(sx, sy));
            // Resize grips on the borderless edges (only when not maximized).
            if (!IsMaxView)
            {
                bool l = p.X <= RESIZE, r = p.X >= ClientSize.Width - RESIZE;
                bool t = p.Y <= RESIZE, b = p.Y >= ClientSize.Height - RESIZE;
                if (t && l) { m.Result = (IntPtr)HTTOPLEFT;     return; }
                if (t && r) { m.Result = (IntPtr)HTTOPRIGHT;    return; }
                if (b && l) { m.Result = (IntPtr)HTBOTTOMLEFT;  return; }
                if (b && r) { m.Result = (IntPtr)HTBOTTOMRIGHT; return; }
                if (l)      { m.Result = (IntPtr)HTLEFT;        return; }
                if (r)      { m.Result = (IntPtr)HTRIGHT;       return; }
                if (t)      { m.Result = (IntPtr)HTTOP;         return; }
                if (b)      { m.Result = (IntPtr)HTBOTTOM;      return; }
            }
            // The title strip (panel/labels are hit-transparent) acts as the caption →
            // native drag, double-click-to-maximize, and Aero snap.
            if (p.Y >= 0 && p.Y < TITLE_H && p.X >= 0 && p.X < ClientSize.Width)
            {
                m.Result = (IntPtr)HTCAPTION; return;
            }
        }
        // Double-click the caption to toggle maximize/restore — via OUR ToggleMax (current monitor),
        // NOT DefWindowProc (which OS-maximizes to monitor 1). The window class has CS_DBLCLKS, so the
        // second caption click arrives as WM_NCLBUTTONDBLCLK; swallow it (don't call base) and defer
        // ToggleMax to a clean message context, like the maximize button's Click handler.
        if (m.Msg == WM_NCLBUTTONDBLCLK && m.WParam.ToInt32() == HTCAPTION)
        {
            BeginInvoke((Action)ToggleMax);
            return;
        }
        // Fallback for the no-CS_DBLCLKS case: detect the double-click from two WM_NCLBUTTONDOWN
        // messages ourselves (first click still starts a drag; a quick second one toggles maximize).
        if (m.Msg == WM_NCLBUTTONDOWN && m.WParam.ToInt32() == HTCAPTION)
        {
            int lp = m.LParam.ToInt32();
            var pt = new Point((short)(lp & 0xFFFF), (short)((lp >> 16) & 0xFFFF)); // screen coords
            int now = Environment.TickCount;
            if (now - _capDownTick <= SystemInformation.DoubleClickTime &&
                Math.Abs(pt.X - _capDownPt.X) <= SystemInformation.DoubleClickSize.Width &&
                Math.Abs(pt.Y - _capDownPt.Y) <= SystemInformation.DoubleClickSize.Height)
            {
                _capDownTick = 0;
                BeginInvoke((Action)ToggleMax);
                return; // swallow → don't start a second drag
            }
            _capDownTick = now; _capDownPt = pt;
            // fall through to base → native HTCAPTION drag
        }
        base.WndProc(ref m);
    }
}

// Title-bar widgets that are transparent to hit-testing: mouse messages fall through to the
// parent form, whose WndProc reports the title strip as HTCAPTION (native drag / dbl-click / snap).
class CaptionPanel : Panel
{
    const int WM_NCHITTEST = 0x84, HTTRANSPARENT = -1;
    protected override void WndProc(ref Message m)
    {
        base.WndProc(ref m);
        if (m.Msg == WM_NCHITTEST) m.Result = (IntPtr)HTTRANSPARENT;
    }
}
