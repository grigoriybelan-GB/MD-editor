static class MdEditorHost
{
    [STAThread]
    static void Main()
    {
        Application.EnableVisualStyles();
        Application.SetCompatibleTextRenderingDefault(false);

        string dir  = AppDomain.CurrentDomain.BaseDirectory;
        string html = Path.Combine(dir, "md-editor.html");
        string ico  = Path.Combine(dir, "md-editor.ico");
        string udf  = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
            "MDEditor", "WebView2");

        // "Open with" / double-click passes the file path as the first arg → load it.
        // An mdeditor:// link (registered URL protocol) arrives the same way, as the whole link.
        string openPath = null;
        string[] argv = Environment.GetCommandLineArgs();
        if (argv.Length > 1)
        {
            string arg = argv[1];
            if (arg.StartsWith("mdeditor:", StringComparison.OrdinalIgnoreCase)) arg = PathFromLink(arg);
            if (arg != null && File.Exists(arg)) openPath = arg;
        }

        Application.Run(new MainForm(html, ico, udf, openPath));
    }

    // mdeditor://C:/path/doc.md (also mdeditor:///C:/… or mdeditor:C:\…, %-escapes allowed) → C:\path\doc.md.
    // Any web page can fire this link, so only a LOCAL DRIVE path to a Markdown/text file is accepted:
    // a UNC / \\host path would make Windows contact that host (and offer credentials) on File.Exists.
    static string PathFromLink(string link)
    {
        string p = link.Substring("mdeditor:".Length);
        int cut = p.IndexOfAny(new[] { '?', '#' });   // a real ? or # in a name arrives %-escaped
        if (cut >= 0) p = p.Substring(0, cut);
        try { p = Uri.UnescapeDataString(p); } catch { return null; }
        p = p.TrimStart('/', '\\').TrimEnd('/').Replace('/', '\\');
        if (!System.Text.RegularExpressions.Regex.IsMatch(p, @"^[A-Za-z]:\\[^\\]")) return null;
        if (!System.Text.RegularExpressions.Regex.IsMatch(p, @"\.(md|markdown|txt)$",
                System.Text.RegularExpressions.RegexOptions.IgnoreCase)) return null;
        return p;
    }
}

