// MD Editor host: a borderless WinForms window with a CUSTOM title bar (app icon +
// "MD Editor" on the left, the current file name centered, and min/maximize/close on
// the right), embedding the Edge WebView2 control to render md-editor.html beneath it.
//
// The page sets document.title to "<file> • — MD Editor"; the host mirrors that into the
// taskbar (Form.Text) and, with the " — MD Editor" suffix stripped, into the centered
// title-bar label.
//
// Requires (next to the exe): md-editor.html, md-editor.ico, md-editor-icon.png (header logo —
// a clean PNG, since GDI+ can't decode this .ico's PNG-compressed frames), the two WebView2 SDK
// DLLs, WebView2Loader.dll (x64), and the Evergreen WebView2 Runtime.
//
// Rebuild (use - switches, not /, from Git Bash):
//   C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe -target:winexe -platform:x64 ^
//     -win32icon:md-editor.ico -out:md-editor.exe ^
//     -reference:Microsoft.Web.WebView2.Core.dll ^
//     -reference:Microsoft.Web.WebView2.WinForms.dll ^
//     launcher.cs

// Win32 version info, generated by csc from these assembly attributes (-win32icon keeps the icon).
// An unsigned, freshly compiled exe with NO version block is a strong Defender ML heuristic signal
// (Trojan:Script/Wacatac.C!ml false positive, 2026-08-26) - keep this populated.
[assembly: AssemblyTitle("MD Editor")]                       // -> FileDescription
[assembly: AssemblyDescription("Split-view Markdown editor - WebView2 host for md-editor.html")]
[assembly: AssemblyCompany("MD Editor")]                     // -> CompanyName (matches MyAppPublisher in md-editor.iss)
[assembly: AssemblyProduct("MD Editor")]                     // -> ProductName
[assembly: AssemblyCopyright("Copyright (c) 2026")]          // -> LegalCopyright
[assembly: AssemblyVersion("1.3.4.0")]
[assembly: AssemblyFileVersion("1.3.4.0")]                   // -> FileVersion / ProductVersion
