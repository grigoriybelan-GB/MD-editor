    // File's last-write time as Unix epoch milliseconds (UTC) — the page's autosave conflict
    // guard compares this. Milliseconds (not ticks) so the value stays exact in a JS Number
    // (ticks overflow 2^53 and would round, causing false conflicts); it also matches the
    // File System Access API's file.lastModified units. 0 if the file is missing/unreadable.
    static readonly DateTime _epoch = new DateTime(1970, 1, 1, 0, 0, 0, DateTimeKind.Utc);
    static long Mtime(string path)
    {
        try { return (long)(File.GetLastWriteTimeUtc(path) - _epoch).TotalMilliseconds; } catch { return 0; }
    }

    // Escape a string for embedding inside a JS double-quoted literal.
    static string EscapeJs(string s)
    {
        if (s == null) return "";
        var sb = new System.Text.StringBuilder(s.Length + 16);
        foreach (char ch in s)
        {
            switch (ch)
            {
                case '\\': sb.Append("\\\\"); break;
                case '"':  sb.Append("\\\""); break;
                case '\n': sb.Append("\\n");  break;
                case '\r': sb.Append("\\r");  break;
                case '\t': sb.Append("\\t");  break;
                default:
                    // Escape control chars and the JS line terminators U+2028 / U+2029.
                    if (ch < 0x20 || ch == (char)0x2028 || ch == (char)0x2029)
                        sb.Append("\\u").Append(((int)ch).ToString("x4"));
                    else sb.Append(ch);
                    break;
            }
        }
        return sb.ToString();
    }

    // ── Host file bridge ──────────────────────────────────────────────────────────
    // The page (loaded over file://, no real OS paths) drives file I/O through here.
    // Commands (page → host) and replies (host → page) are plain strings:
    //   OPEN:                         → show native Open dialog
    //   OPENPATH:<path>               → read that exact file
    //     ↳ reply OPENED:<mtime>\n<path>\n<text>  | OPENERR:<msg> | OPENCANCEL
    //   SAVETO:<path>\n<text>         → write text to path (unconditional: manual save)
    //     ↳ reply SAVED:<mtime>          | SAVEERR:<msg>
    //   SAVEAUTO:<mtime>\n<path>\n<text> → guarded autosave: write ONLY if the file on disk is not
    //                                    newer than <mtime> (the page's last-saved reference)
    //     ↳ reply SAVED:<mtime>          | SAVECONFLICT | SAVEERR:<msg>
    //   SAVEAS:<suggestedName>\n<text> → show native Save dialog, write there
    //     ↳ reply SAVEDAS:<mtime>\n<path> | SAVEASCANCEL | SAVEERR:<msg>
    //   NEWWIN:<path>                 → launch a SECOND MD Editor instance on that file
    //   OPENFOLDER:<path>             → reveal the file in Explorer (no reply)
    // <mtime> = file's last-write time as Unix epoch ms (UTC). <path> never contains a newline.
    void HandleHostMessage(CoreWebView2 c, string msg)
    {
        // DIRTY:1 / DIRTY:0 — the page mirrors its unsaved-changes flag here for the close guard.
        if (msg == "DIRTY:1") { _dirty = true;  return; }
        if (msg == "DIRTY:0") { _dirty = false; return; }
        // CLOSENOW — the page finished a "Save and close"; close without re-prompting.
        if (msg == "CLOSENOW") { _forceClose = true; try { Close(); } catch { } return; }
        if (msg.StartsWith("SAVETO:"))
        {
            string rest = msg.Substring(7);
            int nl = rest.IndexOf('\n');
            if (nl < 0) { Post(c, "SAVEERR:malformed request"); return; }
            string path = rest.Substring(0, nl);
            try { File.WriteAllText(path, rest.Substring(nl + 1)); RememberDir(path); Post(c, "SAVED:" + Mtime(path)); }
            catch (Exception ex) { Post(c, "SAVEERR:" + ex.Message); }
            return;
        }
        if (msg.StartsWith("SAVEAUTO:"))
        {
            // Guarded autosave: refuse if the file changed on disk since the page last saved it,
            // so a background autosave never clobbers an external edit.
            string rest = msg.Substring(9);
            int nl1 = rest.IndexOf('\n');
            int nl2 = nl1 < 0 ? -1 : rest.IndexOf('\n', nl1 + 1);
            if (nl1 < 0 || nl2 < 0) { Post(c, "SAVEERR:malformed request"); return; }
            long expected; bool haveExpected = long.TryParse(rest.Substring(0, nl1), out expected);
            string path = rest.Substring(nl1 + 1, nl2 - nl1 - 1);
            string text = rest.Substring(nl2 + 1);
            try
            {
                // Write ONLY when we can positively confirm the file on disk is still exactly the one
                // the page last read/wrote: a parseable, positive baseline AND an exact mtime match.
                // Any mismatch (newer, older, missing file, or bad baseline) is a conflict, so a
                // background autosave can never overwrite an external edit.
                if (!haveExpected || expected <= 0 || !File.Exists(path) || Mtime(path) != expected)
                {
                    Post(c, "SAVECONFLICT");
                    return;
                }
                File.WriteAllText(path, text);
                RememberDir(path);
                Post(c, "SAVED:" + Mtime(path));
            }
            catch (Exception ex) { Post(c, "SAVEERR:" + ex.Message); }
            return;
        }
        if (msg == "OPEN:")
        {
            using (var ofd = new OpenFileDialog())
            {
                ofd.Title  = "Open";
                ofd.Filter = "Markdown / Text (*.md;*.markdown;*.txt)|*.md;*.markdown;*.txt|All files (*.*)|*.*";
                if (!string.IsNullOrEmpty(_lastDir) && Directory.Exists(_lastDir)) ofd.InitialDirectory = _lastDir;
                if (ofd.ShowDialog(this) == DialogResult.OK)
                {
                    RememberDir(ofd.FileName);
                    try { Post(c, "OPENED:" + Mtime(ofd.FileName) + "\n" + ofd.FileName + "\n" + File.ReadAllText(ofd.FileName)); }
                    catch (Exception ex) { Post(c, "OPENERR:" + ex.Message); }
                }
                else Post(c, "OPENCANCEL");
            }
            return;
        }
        if (msg.StartsWith("OPENPATH:"))
        {
            string path = msg.Substring(9);
            try { Post(c, "OPENED:" + Mtime(path) + "\n" + path + "\n" + File.ReadAllText(path)); RememberDir(path); }
            catch (Exception ex) { Post(c, "OPENERR:" + ex.Message); }
            return;
        }
        if (msg.StartsWith("NEWWIN:"))
        {
            // A linked .md opens in its OWN window instead of replacing the open document: re-launch
            // this exe with the path, which Main() already accepts as argv[1] (the "Open with" entry
            // point). Nothing here touches the current window's state - it keeps its document.
            string path = msg.Substring(7);
            try
            {
                if (!File.Exists(path)) { Post(c, "OPENERR:Could not find file: " + path); return; }
                Process.Start(new ProcessStartInfo {
                    FileName        = Application.ExecutablePath,
                    Arguments       = "\"" + path + "\"",
                    UseShellExecute = true
                });
            }
            catch (Exception ex) { Post(c, "OPENERR:" + ex.Message); }
            return;
        }
        if (msg.StartsWith("SAVEAS:"))
        {
            string rest = msg.Substring(7);
            int nl = rest.IndexOf('\n');
            if (nl < 0) { Post(c, "SAVEERR:malformed request"); return; }
            string sug = rest.Substring(0, nl), text = rest.Substring(nl + 1);
            using (var sfd = new SaveFileDialog())
            {
                sfd.Title    = "Save As";
                sfd.Filter   = "Markdown (*.md)|*.md|All files (*.*)|*.*";
                sfd.FileName = sug;
                if (!string.IsNullOrEmpty(_lastDir) && Directory.Exists(_lastDir)) sfd.InitialDirectory = _lastDir;
                if (sfd.ShowDialog(this) == DialogResult.OK)
                {
                    try { File.WriteAllText(sfd.FileName, text); RememberDir(sfd.FileName); Post(c, "SAVEDAS:" + Mtime(sfd.FileName) + "\n" + sfd.FileName); }
                    catch (Exception ex) { Post(c, "SAVEERR:" + ex.Message); }
                }
                else Post(c, "SAVEASCANCEL");
            }
            return;
        }
        if (msg.StartsWith("OPENFOLDER:"))
        {
            string path = msg.Substring(11);
            try { Process.Start(new ProcessStartInfo { FileName = "explorer.exe", Arguments = "/select,\"" + path + "\"", UseShellExecute = true }); }
            catch { }
            return;
        }
    }
    static void Post(CoreWebView2 c, string s) { try { c.PostWebMessageAsString(s); } catch { } }
    // Remember the folder of the file we just opened/saved, so the next Open/Save As dialog
    // reopens there instead of a generic default.
    void RememberDir(string path)
    {
        try { var d = Path.GetDirectoryName(path); if (!string.IsNullOrEmpty(d)) _lastDir = d; } catch { }
    }

